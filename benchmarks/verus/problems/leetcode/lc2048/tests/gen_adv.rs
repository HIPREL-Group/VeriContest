fn main() {
    let args: Vec<String> = std::env::args().collect();
    let seed = if args.len() > 1 {
        args[1].parse::<u64>().unwrap_or(1)
    } else {
        1
    };

    let mut rng = Rng::new(seed);

    // Emit all boundary values
    let boundaries = boundary_values();
    let mut emitted = 0usize;
    for &b in &boundaries {
        if b >= 0 && b <= 1_000_000 {
            let n = generate_test_case(b);
            println!("{{\"n\":{}}}", n);
            emitted += 1;
        }
    }

    // Fill remaining with random values up to 200 total
    let target_total = 220usize;
    while emitted < target_total {
        let mode = (rng.next_u64() % 6) as u32;
        let v: i32 = match mode {
            0 => rng.gen_range_i32(0, 100),
            1 => rng.gen_range_i32(0, 10_000),
            2 => rng.gen_range_i32(100_000, 1_000_000),
            3 => rng.gen_range_i32(0, 1_000_000),
            4 => {
                // near boundary
                let idx = (rng.next_u64() as usize) % boundaries.len();
                let base = boundaries[idx];
                let delta = rng.gen_range_i32(-3, 3);
                let r = base + delta;
                if r < 0 { 0 } else if r > 1_000_000 { 1_000_000 } else { r }
            }
            _ => rng.gen_range_i32(0, 1_000_000),
        };
        let n = generate_test_case(v);
        println!("{{\"n\":{}}}", n);
        emitted += 1;
    }
}