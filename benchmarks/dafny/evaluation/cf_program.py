"""Code tests of Codeforces problems: the Verus version's program, with the Dafny methods.

A Codeforces testcase is the stdin and stdout of the program in the problem's
description: the `main` of the Verus version's program (main.rs), which reads
the input, calls the entry methods (`Solution::<f>`) and prints what they
return. score.py builds the solution with `dafny build --target:rs` (a library
crate, `solution`) and adds the binary src/bin/cfmain.rs written by
`source(main_rs, sigs, signature)`:

  * the program's `use` items and its `main`, with the functions and constants
    `main` uses (`program`, also shown in the description). `main` is renamed
    and run in a thread with a 1 GiB stack (as the LeetCode harness runs each
    call);
  * an `impl Solution` in which each entry method `f`, with main.rs's Rust
    signature, converts its arguments to the Dafny values of the method's
    parameters, calls the compiled method, and converts its result to the Rust
    return type. An integer result outside the range of that type panics.

The program then runs on each testcase's stdin, as VeriContest's scorer runs
main.rs (score.py: code_tests_cf).
"""

import re

import rust_harness
from rust_harness import IllTyped, seq_elem, tuple_types

STACK = rust_harness.STACK

PRELUDE = """\
// Generated by eval/cf_program.py: conversions between the starter's Rust types
// and the Dafny runtime's.
#[allow(dead_code)]
mod __vc {
    use ::dafny_runtime::{DafnyChar, DafnyInt, DafnyType, Sequence};

    pub trait ToD<D> { fn to_d(&self) -> D; }
    pub trait FromD<R> { fn from_d(&self) -> R; }

    macro_rules! ints { ($($t:ty),*) => { $(
        impl ToD<DafnyInt> for $t {
            fn to_d(&self) -> DafnyInt { DafnyInt::parse_bytes(self.to_string().as_bytes(), 10) }
        }
        impl FromD<$t> for DafnyInt {
            fn from_d(&self) -> $t {
                format!("{:?}", self).parse::<$t>().expect("a result outside the range of its Rust type")
            }
        }
    )* } }
    ints!(i8, i16, i32, i64, i128, isize, u8, u16, u32, u64, u128, usize);

    impl ToD<bool> for bool { fn to_d(&self) -> bool { *self } }
    impl FromD<bool> for bool { fn from_d(&self) -> bool { *self } }
    impl ToD<DafnyChar> for char { fn to_d(&self) -> DafnyChar { DafnyChar(*self) } }
    impl FromD<char> for DafnyChar { fn from_d(&self) -> char { self.0 } }
    impl ToD<Sequence<DafnyChar>> for str {
        fn to_d(&self) -> Sequence<DafnyChar> { Sequence::from_array_owned(self.chars().map(DafnyChar).collect()) }
    }
    impl ToD<Sequence<DafnyChar>> for String {
        fn to_d(&self) -> Sequence<DafnyChar> { self.as_str().to_d() }
    }
    impl FromD<String> for Sequence<DafnyChar> {
        fn from_d(&self) -> String { self.to_array().iter().map(|c| c.0).collect() }
    }
    impl<T: ToD<D>, D: DafnyType> ToD<Sequence<D>> for [T] {
        fn to_d(&self) -> Sequence<D> { Sequence::from_array_owned(self.iter().map(|x| x.to_d()).collect()) }
    }
    impl<T: ToD<D>, D: DafnyType> ToD<Sequence<D>> for Vec<T> {
        fn to_d(&self) -> Sequence<D> { self.as_slice().to_d() }
    }
    impl<T: FromD<R> + DafnyType, R> FromD<Vec<R>> for Sequence<T> {
        fn from_d(&self) -> Vec<R> { self.to_array().iter().map(|x| x.from_d()).collect() }
    }
    impl<'a, T: ToD<D> + ?Sized, D> ToD<D> for &'a T { fn to_d(&self) -> D { (**self).to_d() } }

    macro_rules! tuples { ($(($($a:ident $b:ident $i:tt),+)),*) => { $(
        impl<$($a: ToD<$b>, $b),+> ToD<($($b,)+)> for ($($a,)+) {
            fn to_d(&self) -> ($($b,)+) { ($(self.$i.to_d(),)+) }
        }
        impl<$($a: FromD<$b>, $b),+> FromD<($($b,)+)> for ($($a,)+) {
            fn from_d(&self) -> ($($b,)+) { ($(self.$i.from_d(),)+) }
        }
    )* } }
    tuples!((A0 B0 0, A1 B1 1), (A0 B0 0, A1 B1 1, A2 B2 2), (A0 B0 0, A1 B1 1, A2 B2 2, A3 B3 3),
            (A0 B0 0, A1 B1 1, A2 B2 2, A3 B3 3, A4 B4 4));
"""

# only when a header uses the prelude's datatype, which the solution then declares
OPTION = """
    use ::std::rc::Rc;
    use ::solution::_module::Option as DOption;
    impl<T: ToD<D>, D: DafnyType> ToD<Rc<DOption<D>>> for Option<T> {
        fn to_d(&self) -> Rc<DOption<D>> {
            Rc::new(match self { None => DOption::None {}, Some(x) => DOption::Some { value: x.to_d() } })
        }
    }
    impl<T: FromD<R> + DafnyType, R> FromD<Option<R>> for Rc<DOption<T>> {
        fn from_d(&self) -> Option<R> {
            match &**self { DOption::None {} => None, DOption::Some { value } => Some(value.from_d()) }
        }
    }
"""

MAIN = """
fn main() {
    let worker = ::std::thread::Builder::new().stack_size(%d).spawn(|| { let _ = __vc_main(); }).unwrap();
    let ok = worker.join().is_ok();
    ::std::io::Write::flush(&mut ::std::io::stdout()).ok();
    ::std::process::exit(if ok { 0 } else { 101 });
}
""" % STACK


def dafny_rust_type(ty):
    """The Dafny runtime's Rust type for a Dafny type of a method header."""
    if ty in ("int", "nat"):
        return "::dafny_runtime::DafnyInt"
    if ty == "bool":
        return "bool"
    if ty == "char":
        return "::dafny_runtime::DafnyChar"
    if ty in ("string", "seq<char>"):
        return "::dafny_runtime::Sequence<::dafny_runtime::DafnyChar>"
    if seq_elem(ty) is not None:
        return f"::dafny_runtime::Sequence<{dafny_rust_type(seq_elem(ty))}>"
    if tuple_types(ty) is not None:
        return "(" + ", ".join(dafny_rust_type(t) for t in tuple_types(ty)) + ",)"
    m = re.fullmatch(r"Option<(.*)>", ty)
    if m:
        return f"::std::rc::Rc<::solution::_module::Option<{dafny_rust_type(m.group(1))}>>"
    raise IllTyped(f"no conversion for type {ty}")


def item(text):
    text = text.strip()
    m = re.match(r"(?:pub\s+)?(?:fn|const|static)\s+(\w+)", text)
    return (m.group(1) if m else None, text)


def rust_items(src):
    """The top-level items of Rust source: [(name of a fn, const or static, or None, text)].
    Braces in string and char literals and in comments are skipped."""
    items, depth, start, i = [], 0, 0, 0
    while i < len(src):
        c = src[i]
        if src.startswith("//", i):
            i = src.find("\n", i) if "\n" in src[i:] else len(src)
            continue
        if c == '"':
            i += 1
            while i < len(src) and src[i] != '"':
                i += 2 if src[i] == "\\" else 1
        elif c == "'":
            m = re.match(r"'(\\.|[^\\'])'", src[i:])
            if m:
                i += len(m.group(0)) - 1
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                items.append(item(src[start:i + 1]))
                start = i + 1
        elif c == ";" and depth == 0:
            items.append(item(src[start:i + 1]))
            start = i + 1
        i += 1
    return items


def program(src):
    """`main` of a Codeforces program and the functions and constants it uses, in
    source order (not the `impl Solution` blocks)."""
    named = {n: t for n, t in rust_items(src) if n}
    keep, todo = set(), ["main"]
    while todo:
        n = todo.pop()
        if n in keep or n not in named:
            continue
        keep.add(n)
        todo += [f for f in re.findall(r"(?<![\w:.])([A-Za-z_]\w*)\b", named[n]) if f in named]
    return "\n\n".join(t for n, t in rust_items(src) if n in keep)


def wrapper(sig, rust_sig):
    params, ret = rust_sig
    if len(params) != len(sig["params"]):
        raise IllTyped(f"{sig['rust']}: {len(params)} Rust parameters, {len(sig['params'])} Dafny ones")
    lines, args = [], []
    for i, ((n, _), (_, _, t)) in enumerate(zip(params, sig["params"])):
        lines.append(f"        let d{i}: {dafny_rust_type(t)} = __vc::ToD::to_d(&{n});")
        args.append(f"d{i}" if t == "bool" else f"&d{i}")
    dafny_rust_type(sig["ret"][1])      # a result type without a conversion is an error here
    call = f"::solution::_module::_default::{rust_harness.rust_name(sig['name'])}({', '.join(args)})"
    decl = ", ".join(f"{n}: {t}" for n, t in params)
    return (f"    pub fn {sig['rust']}({decl}) -> {ret} {{\n" + "\n".join(lines) +
            f"\n        let r = {call};\n        __vc::FromD::from_d(&r)\n    }}")


def source(main_rs, sigs, signature):
    """src/bin/cfmain.rs for the entry methods `sigs` (run_tests.cf_entries), from the
    problem's main.rs; `signature` is cf_harness.signature."""
    uses = [t if t.endswith(";") else t + ";" for t in (t for _, t in rust_items(main_rs)) if re.match(r"use\b", t)]
    prog = re.sub(r"fn\s+main\s*\(", "fn __vc_main(", program(main_rs), count=1)
    impl = "impl Solution {\n" + "\n\n".join(wrapper(s, signature(main_rs, s["rust"])) for s in sigs) + "\n}"
    uses_option = any("Option<" in t for s in sigs for t in [s["ret"][1]] + [p[2] for p in s["params"]])
    return ("#![allow(warnings)]\n" + PRELUDE + (OPTION if uses_option else "") + "}\n\n" +
            "\n".join(uses) + "\n\nstruct Solution;\n\n" + prog + "\n\n" + impl + "\n" + MAIN)
